"""Write scenarios/sweep-isl*-osl*-cache*.yaml: the grid lives only in this file.

    python3 utils/serving/gen_sweep_scenarios.py

Spike-verified facts (docs/superpowers/plans/2026-10-17-sweep-scenarios-spike-notes.md):
- `sweep:` is top-level (sibling of `benchmark:`), and `sweep.objectives` is required.
- ISL_INCLUDES_PREFIX=false: the shared prefix is added ON TOP of the dataset's
  `isl`, so `isl = target - round(target*cache/100)` keeps total prompt tokens
  equal to the grid ISL.
- cache 0 => omit `prefix_prompts` entirely (`prompts.cache_bust` is a no-op for
  synthetic datasets); cache 50/90 => `prefix_prompts.shared_system_length`.
- No `scenario:` field (inferencex-agentx-mvp hard-rejects synthetic datasets).
- Request floor: `sla_precision: normal` (1000 requests/probe cap); there is no
  completed-request floor in AIPerf (MIN_REQUESTS_FIELD).
"""

from __future__ import annotations

from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
SCENARIOS_DIR = REPO / "scenarios"
GRID_ISL: dict[str, int] = {"8k": 8192, "32k": 32768, "64k": 65536, "128k": 131072}
GRID_OSL: dict[str, int] = {"512": 512, "1k": 1024}
GRID_CACHE: tuple[int, ...] = (0, 50, 90)
# Default SLO: highest concurrency whose TTFT avg < 8 s and ITL p90 < 50 ms.
DEFAULT_SLO = (
    {"metric_tag": "time_to_first_token", "stat": "avg", "op": "lt", "threshold": 8000.0},
    {"metric_tag": "inter_token_latency", "stat": "p90", "op": "lt", "threshold": 50.0},
)
HEADER = (
    "# Generated by utils/serving/gen_sweep_scenarios.py - do not edit by hand.\n"
    "# Synthetic ISL/OSL/cache-hit workload; AIPerf searches for the highest concurrency\n"
    "# meeting the SLO (docs/superpowers/plans/2026-10-17-sweep-scenarios-spike-notes.md).\n"
)


def scenario_name(isl_label: str, osl_label: str, cache: int) -> str:
    return f"sweep-isl{isl_label}-osl{osl_label}-cache{cache}"


def shared_prefix_tokens(isl: int, cache: int) -> int:
    return round(isl * cache / 100)


def grid() -> list[tuple[str, int, str, int, int]]:
    return [
        (il, iv, ol, ov, cache)
        for il, iv in GRID_ISL.items()
        for ol, ov in GRID_OSL.items()
        for cache in GRID_CACHE
    ]


def build_scenario(isl: int, osl: int, cache: int) -> dict:
    """The parsed YAML mapping for one grid point (structure of the Task 1 file)."""
    prefix = shared_prefix_tokens(isl, cache)
    dataset: dict = {
        "name": "main",
        "type": "synthetic",
        "entries": 1000,
        "randomSeed": 42,
        "isl": isl
        - prefix,  # unique part; prefix is added on top (spike ISL_INCLUDES_PREFIX=false)
        "osl": osl,
    }
    if prefix:
        # cache 0: no prefix_prompts and no cache_bust (no-op for synthetic, spike CACHE0_FIELD)
        dataset["prefix_prompts"] = {"shared_system_length": prefix}
    return {
        "schemaVersion": "2.0",
        "benchmark": {
            "unsafeOverride": True,
            "endpoint": {
                "type": "chat",
                "path": "/v1/chat/completions",
                "streaming": True,
                "useServerTokenCount": True,
                "extra": {"ignore_eos": True},
            },
            "datasets": [dataset],
            "phases": [
                {
                    "name": "profiling",
                    "kind": "profiling",
                    "type": "concurrency",
                    "duration": 300.0,
                    "gracePeriod": 30.0,
                    "failedRequestThreshold": 0.1,
                }
            ],
        },
        "sweep": {
            "type": "adaptive_search",
            "planner": "smooth_isotonic",
            "objectives": [
                {"metric": "output_token_throughput", "stat": "avg", "direction": "maximize"}
            ],
            "search_space": [
                {"path": "phases.profiling.concurrency", "lo": 1, "hi": 512, "kind": "int"}
            ],
            "sla_filters": [dict(f) for f in DEFAULT_SLO],
            "max_iterations": 16,
            "sla_precision": "normal",  # 1000 requests/probe cap (spike MIN_REQUESTS_FIELD)
        },
        "randomSeed": 42,
    }


def _scenario_text(isl: int, osl: int, cache: int) -> str:
    """Render the YAML byte-identical to the Task 1 verified layout.

    Comment-preserving template instead of yaml.safe_dump so the regenerated
    cache-50/8k/512 file diffs clean against the hand-written reference
    (Task 3 equivalence gate).
    """
    prefix = shared_prefix_tokens(isl, cache)
    lines = [
        'schemaVersion: "2.0"',
        "benchmark:",
        "  unsafeOverride: true",
        "  endpoint:",
        "    type: chat",
        "    path: /v1/chat/completions",
        "    streaming: true",
        "    useServerTokenCount: true",
        "    extra:",
        "      ignore_eos: true   # guarantee OSL: server generates exactly max_tokens",
        "  datasets:",
        "  - name: main",
        "    type: synthetic",
        "    entries: 1000",
        "    randomSeed: 42",
        f"    isl: {isl - prefix}"
        + (
            f"             # unique part; prefix_prompts adds {prefix} shared tokens on top"
            if prefix
            else ""
        ),
        f"    osl: {osl}",
    ]
    if prefix:
        lines += ["    prefix_prompts:", f"      shared_system_length: {prefix}"]
    lines += [
        "  phases:",
        "  - name: profiling",
        "    kind: profiling",
        "    type: concurrency",
        "    duration: 300.0",
        "    gracePeriod: 30.0",
        "    failedRequestThreshold: 0.1",
        "sweep:",
        "  type: adaptive_search",
        "  planner: smooth_isotonic",
        "  objectives:",
        "  - {metric: output_token_throughput, stat: avg, direction: maximize}",
        "  search_space:",
        "  - {path: phases.profiling.concurrency, lo: 1, hi: 512, kind: int}",
        "  sla_filters:",
        "  - {metric_tag: time_to_first_token, stat: avg, op: lt, threshold: 8000.0}",
        "  - {metric_tag: inter_token_latency, stat: p90, op: lt, threshold: 50.0}",
        "  max_iterations: 16",
        "  sla_precision: normal",
        "randomSeed: 42",
    ]
    return "\n".join(lines) + "\n"


def main() -> None:
    for il, iv, ol, ov, cache in grid():
        path = SCENARIOS_DIR / f"{scenario_name(il, ol, cache)}.yaml"
        path.write_text(HEADER + _scenario_text(iv, ov, cache))
        print(path.relative_to(REPO))


if __name__ == "__main__":
    main()
